#!/usr/bin/env python3
import csv
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ROADMAP = ROOT / "roadmap"


def text():
    return "\n".join(p.read_text(errors="replace") for p in sorted(ROADMAP.rglob("*.md")) if p.name != "COVERAGE.md")


def found(text, names):
    pat = re.compile(r"(?<!\w)(" + "|".join(sorted((re.escape(n) for n in names), key=len, reverse=True)) + r")(?!\w)")
    return set(pat.findall(text))


def package_of(cls):
    parts = cls.split(".")
    return parts[2] if cls.startswith("mvc.module.") and len(parts) > 3 else parts[0]


def main():
    features = json.loads((ROADMAP / "features.json").read_text())
    owner = {}
    for slug, f in features.items():
        for p in f["client_packages"] + f["proto_packages"]:
            owner[p] = slug

    body = text()

    opcodes = list(csv.DictReader(open(ROOT / "protocol/opcodes.csv", newline="")))
    op_hit = found(body, {r["name"] for r in opcodes})
    op_miss = [r for r in opcodes if r["name"] not in op_hit]

    screens = json.loads((ROOT / "index/screens.json").read_text())["screens"]
    sc_hit = found(body, {s["class"].split(".")[-1] for s in screens})
    sc_miss = [s for s in screens if s["class"].split(".")[-1] not in sc_hit]

    temps = sorted((ROOT / "raw/xml/tempinfos").glob("*.xml"))
    tp_hit = found(body, {t.stem for t in temps})
    tp_miss = [t for t in temps if t.stem not in tp_hit]

    n_op_hit = len(opcodes) - len(op_miss)
    n_sc_hit = len(screens) - len(sc_miss)
    n_tp_hit = len(temps) - len(tp_miss)

    L = ["# Coverage audit (generated)", "",
         "Generated by `tools/coverage.py`. An opcode is covered when its `protocol/opcodes.csv` name appears as a word in some `roadmap/*.md`; a screen when its class name appears; a template when its `raw/xml/tempinfos/` file stem appears. `tools/coverage.py --check` prints the totals without rewriting this file and `--fail` exits non zero while any item is uncovered.", ""]
    L += ["## Summary", "",
          "| Source | Total | Covered | Uncovered |", "|---|---:|---:|---:|",
          f"| Opcodes | {len(opcodes)} | {n_op_hit} | {len(op_miss)} |",
          f"| Opcodes send | {sum(1 for r in opcodes if r['dir'] == 'send')} | {sum(1 for r in opcodes if r['dir'] == 'send' and r not in op_miss)} | {sum(1 for r in op_miss if r['dir'] == 'send')} |",
          f"| Opcodes accept | {sum(1 for r in opcodes if r['dir'] == 'accept')} | {sum(1 for r in opcodes if r['dir'] == 'accept' and r not in op_miss)} | {sum(1 for r in op_miss if r['dir'] == 'accept')} |",
          f"| Registered screens | {len(screens)} | {n_sc_hit} | {len(sc_miss)} |",
          f"| Template files | {len(temps)} | {n_tp_hit} | {len(tp_miss)} |",
          ""]

    if op_miss:
        L += ["## Uncovered opcodes", "",
              "| dir | code | hex | name |", "|---|---:|---|---|"]
        for r in op_miss:
            L.append(f"| {r['dir']} | {r['code']} | {r['code_hex']} | {r['name']} |")
        L.append("")

    if sc_miss:
        L += ["## Uncovered screens", "",
              "| class | module | title | feature |", "|---|---|---|---|"]
        for s in sorted(sc_miss, key=lambda s: s["class"]):
            pkg = package_of(s["class"])
            L.append(f"| {s['class']} | {s['module']} | {s.get('title') or ''} | {owner.get(pkg, 'unassigned package ' + pkg)} |")
        L.append("")

    if tp_miss:
        L += ["## Uncovered templates", "",
              "| file |", "|---|"]
        for t in tp_miss:
            L.append(f"| `raw/xml/tempinfos/{t.name}` |")
        L.append("")

    if "--check" not in sys.argv:
        (ROADMAP / "COVERAGE.md").write_text("\n".join(L))
    print(f"opcodes {n_op_hit}/{len(opcodes)}  screens {n_sc_hit}/{len(screens)}  templates {n_tp_hit}/{len(temps)}")
    if "--fail" in sys.argv and (op_miss or sc_miss or tp_miss):
        sys.exit(1)
    if "--fail" in sys.argv:
        print("full coverage")


if __name__ == "__main__":
    main()
