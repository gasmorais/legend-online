def write_inventory() -> dict:
    ui.main()
    all_classes = json.loads((ROOT / "index" / "classes.json").read_text())
    screens = json.loads((ROOT / "index" / "screens.json").read_text())

    def tagged(fqns):
        return [f"{all_classes[f]['module']}:{f}" for f in sorted(fqns)]

    data = {
        "screens": [{k: s[k] for k in ("kind", "class", "title", "module", "extends", "stats")} for s in screens["screens"]],
        "views": tagged(screens["views"]),
        "managers": tagged(f for f in all_classes if f.rsplit(".", 1)[-1].endswith(("Manager", "Mgr"))),
        "pickgliss_ui": classes(SRC, "com/pickgliss/ui"),
        "proto_messages": tagged(f for f in all_classes if f.startswith("com.road.yishi.proto.")),
        "actions": classes(SRC, "yishi/actions"),
        "mvc": classes(SRC, "mvc"),
        "http_endpoints": find_endpoints(script_roots()),
        "modules": module_summary(),
        "path_manager": path_manager_routes(),
    }
    (ROOT / "index").mkdir(exist_ok=True)
    (ROOT / "index" / "inventory.json").write_text(json.dumps(data, indent=1, ensure_ascii=False))
    return data


