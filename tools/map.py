def clean(text: str) -> str:
    return text.replace("—", "-").replace("–", "-")


def write_doc(path: pathlib.Path, lines: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(clean("\n".join(lines) + "\n"))


def script_roots() -> list[pathlib.Path]:
    return sorted(DECOMPILED.glob("*/scripts"))


def classes(root: pathlib.Path, sub: str) -> list[str]:
    base = root / sub
    if not base.exists():
        return []
    out = []
    for path in base.rglob("*.as"):
        rel = path.relative_to(root).with_suffix("")
        out.append(str(rel).replace("/", "."))
    return sorted(out)


def count_as(rel: str) -> int:
    base = SRC / rel
    return sum(1 for _ in base.rglob("*.as")) if base.exists() else 0


def find_endpoints(roots: list[pathlib.Path]) -> dict[str, list[str]]:
    pattern = re.compile(r'(?:REQUEST_PATH|_requestPath)\s*\+\s*"([A-Za-z0-9_]+)"')
    found: dict[str, list[str]] = defaultdict(list)
    for root in roots:
        if not root.exists():
            continue
        for path in root.rglob("*.as"):
            text = path.read_text(errors="replace")
            for name in pattern.findall(text):
                found[name].append(f"{root.parent.name}:{path.relative_to(root)}")
    return {k: sorted(set(v)) for k, v in sorted(found.items())}


def path_manager_routes() -> list[dict]:
    if not (SRC / "yishi/manager/PathManager.as").exists():
        return []
    return paths.extract()


def module_summary() -> dict[str, dict]:
    out = {}
    for root in script_roots():
        pkgs = Counter(p.relative_to(root).parts[0] for p in root.rglob("*.as") if len(p.relative_to(root).parts) > 1)
        out[root.parent.name] = {"classes": sum(1 for _ in root.rglob("*.as")),
                                 "top_packages": [k for k, _ in pkgs.most_common(5)]}
    return out


AMF_CALL = re.compile(r'sendToServer2\("(\w+)",\[([^\]]*)\]')
AMF_USE = re.compile(r'CastleServiceManager\.instance\.(\w+)\(')


def amf_methods() -> list[dict]:
    src = SRC / "yishi/service/managers/CastleServiceManager.as"
    if not src.exists():
        return []
    text = src.read_text(errors="replace")
    uses: dict[str, list[str]] = defaultdict(list)
    for root in script_roots():
        for path in root.rglob("*.as"):
            for fn in AMF_USE.findall(path.read_text(errors="replace")):
                uses[fn].append(f"{root.parent.name}:{path.relative_to(root)}")
    out = []
    for m in re.finditer(r'public function (\w+)\(([^)]*)\)[^{]*\{(.*?)\n      \}', text, re.S):
        fn, args, body = m.groups()
        if call := AMF_CALL.search(body):
            out.append({"fn": fn, "args": args.strip(), "remote": "ServerRequest." + call.group(1),
                        "params": call.group(2).strip(), "callers": sorted(set(uses.get(fn, [])))})
    return out


