from __future__ import annotations
from dataclasses import dataclass, field


@dataclass
class Col:
    name: str
    sql: str
    attr: str | None
    comment: str = ""
    conv: str | None = None
    fk: str | None = None
    not_null: bool = False

    @property
    def conversion(self) -> str:
        if self.conv:
            return self.conv
        return {"integer": "int", "smallint": "int", "bigint": "bigint", "numeric": "numeric",
                "boolean": "bool", "integer[]": "csv_int", "text[]": "csv_text"}.get(self.sql, "text")


@dataclass
class Table:
    name: str
    template_set: str
    comment: str
    pk: list[str]
    cols: list[Col]
    mechanic: str = ""
    unique: list[list[str]] = field(default_factory=list)
    source_ref: str = ""

    @property
    def surrogate(self) -> bool:
        return self.pk == ["row_id"]


